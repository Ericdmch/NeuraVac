"""Give the robot's USB devices stable names: /dev/neuravac_{roomba,lidar,camera}.

Linux hands out /dev/ttyUSB0, /dev/ttyUSB1, /dev/video0 ... in plug-in order, so
the numbers change between boots and replugs. This tool asks you to unplug and
replug each device once, works out how to recognise it, and writes a udev rule
that creates a fixed symlink for it.

    python3 udev_setup.py             # guided; prints the rules
    python3 udev_setup.py --install   # guided; installs them (asks for sudo)

Recognition strategy per device:
  * USB serial number, when the adapter has a unique one. The device is found
    again on any port.
  * Otherwise the physical USB port. Cheap USB-serial chips (CH340, many CP210x)
    have no serial number, and two identical adapters look the same, so the
    device must stay in the same port (or the same port of the same hub).
"""

import argparse
import glob
import os
import subprocess
import sys
import time

RULES_PATH = '/etc/udev/rules.d/99-neuravac.rules'

# name -> (kind, human description)
DEVICES = {
    'roomba': ('serial', 'Roomba USB-serial cable'),
    'lidar': ('serial', 'LiDAR USB cable'),
    'camera': ('video', 'webcam'),
}

NODE_GLOBS = {
    'serial': ['/dev/ttyUSB*', '/dev/ttyACM*'],
    'video': ['/dev/video*'],
}


def list_nodes(kind):
    nodes = set()
    for pattern in NODE_GLOBS[kind]:
        nodes.update(glob.glob(pattern))
    return nodes


def udev_properties(node):
    """Return the udev property dict (ID_PATH, ID_SERIAL_SHORT, ...) for a node."""
    result = subprocess.run(
        ['udevadm', 'info', '--query=property', f'--name={node}'],
        capture_output=True, text=True, check=True,
    )
    props = {}
    for line in result.stdout.splitlines():
        key, sep, value = line.partition('=')
        if sep:
            props[key] = value
    return props


def pick_video_node(nodes, props_by_node):
    """A webcam exposes several /dev/video* nodes; pick the capture one."""
    def is_capture(node):
        return ':capture:' in props_by_node[node].get('ID_V4L_CAPABILITIES', '')

    def index(node):
        try:
            name = os.path.basename(node)
            with open(f'/sys/class/video4linux/{name}/index') as handle:
                return int(handle.read().strip())
        except (OSError, ValueError):
            return 99

    return sorted(nodes, key=lambda n: (not is_capture(n), index(n), n))[0]


def identity(props):
    """(vendor id, product id, serial) for a device, serial may be ''."""
    return (
        props.get('ID_VENDOR_ID', ''),
        props.get('ID_MODEL_ID', ''),
        props.get('ID_SERIAL_SHORT', ''),
    )


def choose_methods(selected):
    """Decide how to recognise each device.

    ``selected`` maps name -> udev properties. Returns name -> 'serial' or
    'path'. A serial number is only trusted when present and not shared with
    another selected device (some adapters ship with a generic serial).
    """
    methods = {}
    ids = {name: identity(props) for name, props in selected.items()}
    for name, key in ids.items():
        vendor, product, serial = key
        duplicated = sum(1 for other in ids.values() if other == key) > 1
        methods[name] = 'serial' if (vendor and product and serial and not duplicated) \
            else 'path'
    return methods


def build_rule(name, kind, props, method):
    """Return one udev rule line that creates /dev/neuravac_<name>."""
    if kind == 'serial':
        match = ['SUBSYSTEM=="tty"']
        access = 'GROUP="dialout", MODE="0660"'
    else:
        match = ['SUBSYSTEM=="video4linux"', 'ATTR{index}=="0"']
        access = 'GROUP="video", MODE="0660"'

    if method == 'serial':
        vendor, product, serial = identity(props)
        match += [
            f'ENV{{ID_VENDOR_ID}}=="{vendor}"',
            f'ENV{{ID_MODEL_ID}}=="{product}"',
            f'ENV{{ID_SERIAL_SHORT}}=="{serial}"',
        ]
    else:
        path = props.get('ID_PATH', '')
        if not path:
            raise ValueError(f'{name}: udev reports no ID_PATH, cannot build a rule')
        match.append(f'ENV{{ID_PATH}}=="{path}"')

    return ', '.join(match + [f'SYMLINK+="neuravac_{name}"', access])


def build_rules(selected, methods):
    lines = [
        '# NeuraVac stable device names. Generated by bringup/udev_setup.py.',
        '# Re-run the tool if you move a device to a different USB port and the',
        '# rule for it says "port".',
    ]
    for name, props in selected.items():
        kind = DEVICES[name][0]
        lines.append(f'# {name}: matched by {methods[name]} '
                     f'({"/".join(identity(props)[:2]) or "unknown id"})')
        lines.append(build_rule(name, kind, props, methods[name]))
    return '\n'.join(lines) + '\n'


def merge_rules(existing_text, generated_text):
    """Replace newly selected device rules while preserving the other links."""
    def entries(text):
        lines = text.splitlines()
        found = {}
        for index, line in enumerate(lines[:-1]):
            if line.startswith('# ') and ': matched by ' in line:
                name = line[2:].split(':', 1)[0]
                if name in DEVICES and f'SYMLINK+="neuravac_{name}"' in lines[index + 1]:
                    found[name] = [line, lines[index + 1]]
        return found

    generated_lines = generated_text.splitlines()
    merged = entries(existing_text)
    merged.update(entries(generated_text))
    lines = generated_lines[:3]
    for name in DEVICES:
        lines.extend(merged.get(name, []))
    return '\n'.join(lines) + '\n'


def detect(name, kind, prompt=input, sleep=time.sleep):
    """Unplug/replug one device and return the udev properties of the new node."""
    description = DEVICES[name][1]
    prompt(f'\n[{name}] Unplug the {description}, then press Enter... ')
    sleep(1.0)
    before = list_nodes(kind)
    prompt(f'[{name}] Plug the {description} back in, wait 3 seconds, '
           f'then press Enter... ')
    sleep(1.0)
    new = list_nodes(kind) - before
    if not new:
        raise RuntimeError(
            f'No new {kind} device appeared after replugging the {description}. '
            f'Check the cable and that it was unplugged first.'
        )
    props_by_node = {node: udev_properties(node) for node in new}
    if kind == 'video':
        node = pick_video_node(new, props_by_node)
    elif len(new) == 1:
        node = next(iter(new))
    else:
        raise RuntimeError(
            f'{len(new)} devices appeared at once ({", ".join(sorted(new))}); '
            f'replug only the {description}.'
        )
    print(f'  found {node}')
    return props_by_node[node]


def install(rules_text):
    """Write the rules file with sudo and reload udev."""
    subprocess.run(['sudo', 'tee', RULES_PATH], input=rules_text, text=True,
                   stdout=subprocess.DEVNULL, check=True)
    subprocess.run(['sudo', 'udevadm', 'control', '--reload-rules'], check=True)
    subprocess.run(['sudo', 'udevadm', 'trigger'], check=True)


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__.split('\n\n')[0])
    parser.add_argument('--install', action='store_true',
                        help=f'write {RULES_PATH} and reload udev (uses sudo)')
    parser.add_argument('--only', nargs='+', choices=sorted(DEVICES),
                        help='configure only these devices')
    args = parser.parse_args(argv)

    names = args.only or list(DEVICES)
    selected = {}
    try:
        for name in names:
            selected[name] = detect(name, DEVICES[name][0])
    except (RuntimeError, subprocess.CalledProcessError, FileNotFoundError) as error:
        print(f'error: {error}', file=sys.stderr)
        return 1

    methods = choose_methods(selected)
    try:
        rules = build_rules(selected, methods)
        try:
            with open(RULES_PATH, encoding='utf-8') as existing_file:
                rules = merge_rules(existing_file.read(), rules)
        except FileNotFoundError:
            pass
    except ValueError as error:
        print(f'error: {error}', file=sys.stderr)
        return 1

    print('\n' + rules)
    if 'path' in methods.values():
        print('Devices matched by "path" must stay in the same physical USB port.')

    if args.install:
        install(rules)
        print(f'Installed {RULES_PATH}. Replug the devices, then check:')
    else:
        print(f'Not installed. Re-run with --install, or save the rules above to '
              f'{RULES_PATH} and run:\n'
              f'  sudo udevadm control --reload-rules && sudo udevadm trigger\n'
              f'Then check:')
    print('  ls -l /dev/neuravac_*')
    print('Your user must be in the dialout and video groups '
          '(sudo usermod -aG dialout,video $USER, then log out and in).')
    return 0


if __name__ == '__main__':
    sys.exit(main())
